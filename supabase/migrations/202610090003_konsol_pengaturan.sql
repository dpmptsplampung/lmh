-- ============================================================
-- 1. Tabel
-- ============================================================
CREATE TABLE IF NOT EXISTS public.rahasia_pengaturan (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nama        text NOT NULL CHECK (char_length(nama) BETWEEN 1 AND 80),
  ciphertext  text NOT NULL,
  iv          text NOT NULL,
  tag         text NOT NULL,
  key_id      smallint NOT NULL DEFAULT 1,
  last4       text NOT NULL DEFAULT '' CHECK (char_length(last4) <= 4),
  diubah_oleh uuid REFERENCES public.petugas(id) ON DELETE SET NULL,
  diubah_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.pengaturan_sistem (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  kategori      text NOT NULL CHECK (char_length(kategori) BETWEEN 1 AND 40),
  kunci         text NOT NULL CHECK (kunci ~ '^[a-z0-9_.]{3,64}$'),
  nilai         jsonb NOT NULL,
  versi         integer NOT NULL CHECK (versi > 0),
  status        text NOT NULL CHECK (status IN ('draf', 'aktif', 'arsip')),
  alasan        text CHECK (alasan IS NULL OR char_length(alasan) <= 500),
  hasil_uji     jsonb NOT NULL DEFAULT '{}'::jsonb,
  diuji_at      timestamptz,
  diubah_oleh   uuid REFERENCES public.petugas(id) ON DELETE SET NULL,
  dibuat_at     timestamptz NOT NULL DEFAULT now(),
  diaktifkan_at timestamptz,
  CONSTRAINT pengaturan_sistem_kunci_versi_key UNIQUE (kunci, versi)
);
-- Paling banyak satu versi aktif dan satu draf per kunci.
CREATE UNIQUE INDEX IF NOT EXISTS uq_pengaturan_aktif ON public.pengaturan_sistem (kunci) WHERE status = 'aktif';
CREATE UNIQUE INDEX IF NOT EXISTS uq_pengaturan_draf  ON public.pengaturan_sistem (kunci) WHERE status = 'draf';

CREATE TABLE IF NOT EXISTS public.pengaturan_riwayat (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kunci      text NOT NULL,
  aksi       text NOT NULL CHECK (aksi IN ('simpan_draf', 'aktifkan', 'rollback')),
  versi_lama integer,
  versi_baru integer NOT NULL,
  alasan     text,
  oleh       uuid REFERENCES public.petugas(id) ON DELETE SET NULL,
  at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_pengaturan_riwayat_kunci ON public.pengaturan_riwayat (kunci, at DESC);

ALTER TABLE public.rahasia_pengaturan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pengaturan_sistem  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pengaturan_riwayat ENABLE ROW LEVEL SECURITY;
-- Sengaja TANPA policy: anon/authenticated tidak punya jalur sama sekali.
REVOKE ALL ON TABLE public.rahasia_pengaturan FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.pengaturan_sistem  FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.pengaturan_riwayat FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.rahasia_pengaturan TO service_role;
GRANT ALL ON TABLE public.pengaturan_sistem  TO service_role;
GRANT ALL ON TABLE public.pengaturan_riwayat TO service_role;

